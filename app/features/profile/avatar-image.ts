export const AVATAR_ACCEPT = "image/jpeg,image/png,image/webp"
export const MAX_AVATAR_INPUT_BYTES = 8 * 1024 * 1024
export const MAX_AVATAR_OUTPUT_BYTES = 500 * 1024
export const AVATAR_EDGE_PX = 512
const SUPPORTED_TYPES = new Set(["image/jpeg", "image/png", "image/webp"])

export class AvatarImageError extends Error {}

export function validateAvatarFile(file: Pick<File, "type" | "size">) {
  if (!SUPPORTED_TYPES.has(file.type)) {
    throw new AvatarImageError("Choose a JPEG, PNG or WebP image.")
  }
  if (file.size > MAX_AVATAR_INPUT_BYTES) {
    throw new AvatarImageError("Choose an image smaller than 8 MB.")
  }
}

function loadImage(url: string) {
  return new Promise<HTMLImageElement>((resolve, reject) => {
    const image = new Image()
    image.onload = () => resolve(image)
    image.onerror = () =>
      reject(new AvatarImageError("That image couldn't be opened."))
    image.src = url
  })
}

function canvasBlob(canvas: HTMLCanvasElement, quality: number) {
  return new Promise<Blob>((resolve, reject) => {
    canvas.toBlob(
      (blob) =>
        blob
          ? resolve(blob)
          : reject(new AvatarImageError("That image couldn't be processed.")),
      "image/jpeg",
      quality
    )
  })
}

function blobDataUrl(blob: Blob) {
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () =>
      typeof reader.result === "string"
        ? resolve(reader.result)
        : reject(new AvatarImageError("That image couldn't be read."))
    reader.onerror = () =>
      reject(new AvatarImageError("That image couldn't be read."))
    reader.readAsDataURL(blob)
  })
}

/**
 * Centre-crops, downsizes and re-encodes an uploaded image. The persisted value
 * is generated by us, so arbitrary data URLs and active SVG content never enter
 * IndexedDB or backups.
 */
export async function prepareAvatar(file: File) {
  validateAvatarFile(file)
  const url = URL.createObjectURL(file)
  try {
    const image = await loadImage(url)
    const sourceSize = Math.min(image.naturalWidth, image.naturalHeight)
    if (sourceSize < 1)
      throw new AvatarImageError("That image has no usable pixels.")
    const sx = (image.naturalWidth - sourceSize) / 2
    const sy = (image.naturalHeight - sourceSize) / 2
    const canvas = document.createElement("canvas")
    canvas.width = AVATAR_EDGE_PX
    canvas.height = AVATAR_EDGE_PX
    const ctx = canvas.getContext("2d")
    if (!ctx)
      throw new AvatarImageError(
        "Image processing isn't supported in this browser."
      )
    // JPEG has no transparency; use a warm neutral behind transparent PNGs.
    ctx.fillStyle = "#f6efe3"
    ctx.fillRect(0, 0, canvas.width, canvas.height)
    ctx.drawImage(
      image,
      sx,
      sy,
      sourceSize,
      sourceSize,
      0,
      0,
      canvas.width,
      canvas.height
    )

    for (const quality of [0.86, 0.74, 0.62]) {
      const blob = await canvasBlob(canvas, quality)
      if (blob.size <= MAX_AVATAR_OUTPUT_BYTES) return blobDataUrl(blob)
    }
    throw new AvatarImageError(
      "The processed photo is still too large. Try a simpler image."
    )
  } finally {
    URL.revokeObjectURL(url)
  }
}
